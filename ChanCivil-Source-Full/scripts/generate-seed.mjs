// Generates supabase/seed.sql from the sample data in src/data/.
// Run from the project folder:   node scripts/generate-seed.mjs
// Needs Node.js 22.18 or newer (it reads the .ts data files directly).
//
// Why a script: the website's sample content and the database seed stay identical,
// and nothing has to be copied by hand.

import { writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const load = (p) => import(pathToFileURL(resolve(root, p)).href);

const { articleCategories, resourceCategories } = await load('src/data/categories.ts');
const { sampleArticles } = await load('src/data/articles.ts');
const { sampleResources } = await load('src/data/resources.ts');

// ---- SQL literal helpers -----------------------------------------------------
const q = (s) => `'${String(s).replaceAll("'", "''")}'`;
const dq = (s) => {
  if (String(s).includes('$chancivil$')) throw new Error('content contains the dollar-quote tag');
  return `$chancivil$${s}$chancivil$`;
};
const text = (s) => (s === null || s === undefined ? 'null' : q(s));
const bool = (b) => (b ? 'true' : 'false');
const arr = (a) => (a.length ? `array[${a.map(q).join(', ')}]::text[]` : "'{}'::text[]");
const slugify = (s) =>
  s.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '');

const out = [];
const add = (s = '') => out.push(s);

add('-- =============================================================================');
add('-- ChanCivil seed data. GENERATED by scripts/generate-seed.mjs: do not edit by hand.');
add('-- Run AFTER the three migrations. Safe to run twice (it skips rows that exist).');
add('--');
add('-- Contains: categories, tags, website settings, 8 sample articles (published),');
add('-- and 6 sample resource listings. Sample resources have NO files yet: free ones are');
add('-- DRAFTS until you upload a file in the dashboard and publish them.');
add('-- Sample articles have no author account (author_id is empty).');
add('-- =============================================================================');
add();
add('begin;');
add();

// ---- categories --------------------------------------------------------------
add('-- Categories');
add('insert into public.categories (kind, slug, name_en, name_km, description_en, description_km, icon, sort_order) values');
const catRows = [
  ...articleCategories.map((c, i) => ['article', c, i]),
  ...resourceCategories.map((c, i) => ['resource', c, i]),
].map(
  ([kind, c, i]) =>
    `  (${q(kind)}, ${q(c.slug)}, ${q(c.name.en)}, ${q(c.name.km)}, ${q(c.description.en)}, ${q(c.description.km)}, ${q(c.icon)}, ${(i + 1) * 10})`,
);
add(catRows.join(',\n'));
add('on conflict (kind, slug) do nothing;');
add();

// ---- tags --------------------------------------------------------------------
const tagNames = [...new Set(sampleArticles.flatMap((a) => a.tags))];
add('-- Tags (Khmer names left empty: the website falls back to English)');
add('insert into public.tags (slug, name_en) values');
add(tagNames.map((t) => `  (${q(slugify(t))}, ${q(t)})`).join(',\n'));
add('on conflict (slug) do nothing;');
add();

// ---- settings ----------------------------------------------------------------
add('-- Website settings (the Super Admin edits these in the dashboard)');
add('insert into public.website_settings (key, value) values');
const settings = [
  ['site_title', { en: 'ChanCivil', km: 'ChanCivil' }],
  [
    'site_description',
    {
      en: 'Practical civil and structural engineering knowledge, resources and tools.',
      km: 'ចំណេះដឹង ធនធាន និងឧបករណ៍វិស្វកម្មសំណង់ស៊ីវិល និងរចនាសម្ព័ន្ធជាក់ស្តែង។',
    },
  ],
  ['contact_email', ''],
  ['facebook_url', ''],
  ['youtube_url', ''],
  ['tiktok_url', ''],
  ['telegram_url', ''],
  ['default_language', 'en'],
  ['logo_path', ''],
  ['seo_default_title', { en: 'ChanCivil — Engineering Knowledge. Built for Practice.', km: 'ChanCivil — ចំណេះដឹងវិស្វកម្ម។ សម្រាប់ការអនុវត្តជាក់ស្តែង។' }],
  ['seo_default_description', { en: 'Articles, calculation templates and design resources for civil and structural engineers.', km: 'អត្ថបទ ទម្រង់គណនា និងធនធានរចនា សម្រាប់វិស្វករសំណង់ស៊ីវិល និងរចនាសម្ព័ន្ធ។' }],
];
add(settings.map(([k, v]) => `  (${q(k)}, ${q(JSON.stringify(v))}::jsonb)`).join(',\n'));
add('on conflict (key) do nothing;');
add();

// ---- articles ----------------------------------------------------------------
add('-- Sample articles');
for (const a of sampleArticles) {
  add(`insert into public.articles (slug, title_en, title_km, description_en, description_km, content_en, content_km,`);
  add(`  cover_alt_en, cover_alt_km, status, featured, published_at, read_minutes, code_references)`);
  add(
    `select ${q(a.slug)}, ${q(a.title.en)}, ${q(a.title.km)}, ${q(a.description.en)}, ${q(a.description.km)},\n` +
      `  ${dq(a.content.en)},\n  ${dq(a.content.km)},\n` +
      `  ${q(a.coverAlt.en)}, ${q(a.coverAlt.km)}, 'published', ${bool(a.featured)}, ${q(a.publishedAt + 'T08:00:00+07:00')}::timestamptz, ${a.readMinutes}, ${arr(a.references)}`,
  );
  add(`where not exists (select 1 from public.articles where slug = ${q(a.slug)});`);
  add();
  add(`insert into public.article_categories (article_id, category_id)`);
  add(
    `select a.id, c.id from public.articles a join public.categories c on c.kind = 'article' and c.slug = ${q(a.categorySlug)}\n` +
      `where a.slug = ${q(a.slug)} on conflict do nothing;`,
  );
  add();
  if (a.tags.length) {
    add(`insert into public.article_tags (article_id, tag_id)`);
    add(
      `select a.id, t.id from public.articles a join public.tags t on t.slug in (${a.tags.map((t) => q(slugify(t))).join(', ')})\n` +
        `where a.slug = ${q(a.slug)} on conflict do nothing;`,
    );
    add();
  }
}

// ---- resources ---------------------------------------------------------------
add('-- Sample resource listings (no files uploaded yet)');
for (const r of sampleResources) {
  // A free resource cannot be published without a file, so free samples start as drafts.
  const status = r.isFree ? 'draft' : 'published';
  add(`insert into public.resources (slug, name_en, name_km, description_en, description_km, category_id, file_format,`);
  add(`  version, is_free, price_amount, status, featured, published_at)`);
  add(
    `select ${q(r.slug)}, ${q(r.name.en)}, ${q(r.name.km)}, ${q(r.description.en)}, ${q(r.description.km)},\n` +
      `  (select id from public.categories where kind = 'resource' and slug = ${q(r.categorySlug)}),\n` +
      `  ${q(r.format)}, ${q(r.version)}, ${bool(r.isFree)}, null, ${q(status)}, ${bool(r.featured)}, ${r.isFree ? 'null' : `${q(r.publishedAt + 'T08:00:00+07:00')}::timestamptz`}`,
  );
  add(`where not exists (select 1 from public.resources where slug = ${q(r.slug)});`);
  add();
}

add('commit;');
add();

const target = resolve(root, 'supabase/seed.sql');
mkdirSync(dirname(target), { recursive: true });
writeFileSync(target, out.join('\n'), 'utf8');
console.log(`Wrote ${target}`);
console.log(`  categories: ${articleCategories.length + resourceCategories.length}, tags: ${tagNames.length}, articles: ${sampleArticles.length}, resources: ${sampleResources.length}`);
